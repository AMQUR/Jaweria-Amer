#!/usr/bin/env npx tsx
/**
 * Build the public M/J 2026 results dataset from the private form export.
 *
 *   npx tsx scripts/results/build-mj26-results.ts [--source scripts/source/mj26_source.csv]
 *
 * Reads:  scripts/source/mj26_source.csv                   (git-ignored, PII, never committed)
 * Writes: src/lib/results/mj-2026.public.json              (public-safe, committed)
 *         src/lib/results/mj-2026.audit.json               (public-safe audit: counts + hold reasons only)
 *         docs/results/MJ26_RESULTS_METHODOLOGY.md         (generated section)
 *         scripts/source/mj26-holds.private.json           (private: row → hold reason, for the owner)
 *         scripts/source/mj26-photo-manifest.private.json  (private: archive id → Drive file id)
 *
 * The build is deterministic for a given source file (generatedAt aside).
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { createHash } from "node:crypto";
import { csvToObjects } from "../../src/lib/results/csv";
import { assertDatasetIsPublicSafe, buildMj26Dataset, GRADE_ORDER, type Mj26Dataset } from "../../src/lib/results/mj26-pipeline";

const args = process.argv.slice(2);
const sourceArg = args.includes("--source")
  ? args[args.indexOf("--source") + 1]
  : process.env.MJ26_RESULTS_SOURCE || "scripts/source/mj26_source.csv";
const root = process.cwd();
const sourcePath = path.resolve(root, sourceArg);
if (!fs.existsSync(sourcePath)) {
  console.error(`source not found: ${sourcePath}`);
  process.exit(2);
}

const csv = fs.readFileSync(sourcePath, "utf8");
const fingerprint = createHash("sha256").update(csv).digest("hex").slice(0, 16);
const rows = csvToObjects(csv);
const publicPath = path.resolve(root, "src/lib/results/mj-2026.public.json");
const auditPath = path.resolve(root, "src/lib/results/mj-2026.audit.json");
const previous: Mj26Dataset | null = fs.existsSync(publicPath) ? JSON.parse(fs.readFileSync(publicPath, "utf8")) : null;
const generatedAt = previous && previous.sourceFingerprint === fingerprint ? previous.generatedAt : new Date().toISOString();

const { dataset, holds, photoManifest } = buildMj26Dataset(rows, { generatedAt, sourceFingerprint: fingerprint });
assertDatasetIsPublicSafe(dataset);

fs.mkdirSync(path.dirname(publicPath), { recursive: true });
fs.writeFileSync(publicPath, JSON.stringify(dataset, null, 2) + "\n");

// Public-safe audit: aggregate counts and reasons only — never row ids, names or links.
const previousAudit = fs.existsSync(auditPath) ? JSON.parse(fs.readFileSync(auditPath, "utf8")) : {};
const audit = {
  source: "English With Miss Jay M/J 26 Results (Responses) — Google Form export (CSV)",
  sourceFingerprint: fingerprint,
  generatedAt,
  summary: dataset.summary,
  holdsByReason: dataset.summary.holdsByReason,
  portraits: previousAudit.portraits ?? null,
};
fs.writeFileSync(auditPath, JSON.stringify(audit, null, 2) + "\n");

const privateDir = path.resolve(root, "scripts/source");
fs.mkdirSync(privateDir, { recursive: true });
fs.writeFileSync(path.join(privateDir, "mj26-holds.private.json"), JSON.stringify(holds, null, 2) + "\n");
fs.writeFileSync(path.join(privateDir, "mj26-photo-manifest.private.json"), JSON.stringify(photoManifest, null, 2) + "\n");

const s = dataset.summary;
const pct = (n: number | null) => (n === null ? "—" : `${n.toFixed(1)}%`);
const gradeTable = (label: string, c: typeof s.graded) =>
  `| ${label} | ${c.total} | ${GRADE_ORDER.map((g) => c.byGrade[g]).join(" | ")} | ${c.aOrAStar} | ${pct(c.aOrAStarPct)} |`;

const methodology = `<!-- GENERATED by scripts/results/build-mj26-results.ts — do not edit by hand -->
## Generated figures (source fingerprint \`${fingerprint}\`, generated ${generatedAt})

### Denominators

| Denominator | Count | Meaning |
|---|---:|---|
| Raw form responses | ${s.rawResponses} | every non-blank row in the export |
| Incomplete rows | ${s.incompleteRows} | no e-mail, no name and no grade — dropped |
| Exact duplicates removed | ${s.exactDuplicatesRemoved} | same e-mail + name + grade + syllabus; latest submission kept |
| Ambiguous duplicates held | ${s.ambiguousDuplicates} | same e-mail + name but conflicting grade/syllabus; all rows held |
| **Unique result records** | **${s.uniqueRecords}** | one row per student-per-syllabus after de-duplication |
| Unique students | ${s.uniqueStudents} | distinct e-mail + name identities (${s.multiSyllabusStudents} sat more than one syllabus) |
| Grade unclassified | ${s.gradeUnclassified} | answered "Other" or blank — never counted as any grade |
| Syllabus unknown | ${s.syllabusUnknown} | qualification blank — excluded from public evidence |
| **Graded unique records** | **${s.graded.total}** | unique records with a Cambridge grade A*–U |
| Private / held | ${s.privateRecords} | student asked to keep the result private, gave no answer, or gave conflicting answers |
| **Publicly shareable records** | **${s.shareable.total}** | student answered "Yes, with my name" or "Yes, but hide my name" |

### Grade distribution

| Set | Records | ${GRADE_ORDER.join(" | ")} | A/A* | A/A* % |
|---|---:|${GRADE_ORDER.map(() => "---:").join("|")}|---:|---:|
${gradeTable("All graded unique records (internal reference)", s.graded)}
${gradeTable("Publicly shareable records (what the website shows)", s.shareable)}
${(["1123", "0500", "0510", "9093"] as const)
  .filter((code) => s.shareable.bySyllabus[code].total > 0)
  .map((code) => gradeTable(`Shareable · ${code}`, s.shareable.bySyllabus[code]))
  .join("\n")}

### Identity levels inside the shareable set

| Level | Count |
|---|---:|
| Named (student chose "Yes, with my name") | ${s.shareable.named} |
| Anonymised (student chose "Yes, but hide my name") | ${s.shareable.anonymous} |
| Portrait consented and supplied (named + "Yes, I will upload one" + file present) | ${s.shareable.withPhoto} |

### Holds by reason

| Reason | Rows |
|---|---:|
${Object.entries(s.holdsByReason)
  .filter(([, n]) => n > 0)
  .map(([k, n]) => `| \`${k}\` | ${n} |`)
  .join("\n")}
`;

const docPath = path.resolve(root, "docs/results/MJ26_RESULTS_METHODOLOGY.md");
const marker = "<!-- GENERATED";
let doc = fs.existsSync(docPath) ? fs.readFileSync(docPath, "utf8") : "";
const idx = doc.indexOf(marker);
doc = (idx >= 0 ? doc.slice(0, idx) : doc) + methodology;
fs.mkdirSync(path.dirname(docPath), { recursive: true });
fs.writeFileSync(docPath, doc);

console.log(`✓ ${path.relative(root, publicPath)} (${dataset.records.length} public records)`);
console.log(`  raw ${s.rawResponses} → unique ${s.uniqueRecords} → graded ${s.graded.total} → shareable ${s.shareable.total}`);
console.log(`  shareable A* ${s.shareable.aStar} · A ${s.shareable.a} · A/A* ${s.shareable.aOrAStar} (${pct(s.shareable.aOrAStarPct)}) · named ${s.shareable.named} · anon ${s.shareable.anonymous} · photo-consented ${s.shareable.withPhoto}`);
console.log(`  holds: ${holds.length} (see scripts/source/mj26-holds.private.json)`);
